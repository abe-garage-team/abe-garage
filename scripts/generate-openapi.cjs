const fs = require('node:fs');
const path = require('node:path');
const prettier = require('prettier');

const root = path.resolve(__dirname, '..');
const contractsPath = path.join(root, 'docs/api/contracts.json');
const outputPath = path.join(root, 'docs/api/openapi.json');

function schemaForExample(value) {
  if (typeof value === 'boolean') return { type: 'boolean' };
  if (typeof value === 'number') return { type: Number.isInteger(value) ? 'integer' : 'number' };
  return { type: 'string' };
}

function toOpenApiPath(endpointPath, basePath) {
  if (!endpointPath.startsWith(basePath)) {
    throw new Error(`Endpoint path must begin with ${basePath}: ${endpointPath}`);
  }
  const localPath = endpointPath.slice(basePath.length) || '/';
  return localPath.replace(/:([A-Za-z][A-Za-z0-9_]*)/g, '{$1}');
}

function featureTag(endpointPath, basePath) {
  const segments = endpointPath.slice(basePath.length).split('/').filter(Boolean);
  return segments[0] || 'setup';
}

function buildOpenApi(contracts) {
  const basePath = contracts.base_path.replace(/\/$/, '');
  const openapi = {
    openapi: '3.0.3',
    info: {
      title: `${contracts.project} API`,
      version: '1.0.0',
      description:
        'Generated from docs/api/contracts.json. Do not edit this file directly; run npm run generate:openapi.',
    },
    servers: [{ url: 'http://localhost:5000/api', description: 'Local development server' }],
    paths: {},
    components: {
      securitySchemes: {
        BearerAuth: { type: 'http', scheme: 'bearer', bearerFormat: 'JWT' },
        SetupKey: { type: 'apiKey', in: 'header', name: 'X-Setup-Key' },
      },
    },
  };

  for (const endpoint of contracts.endpoints) {
    const pathKey = toOpenApiPath(endpoint.path, basePath);
    const method = endpoint.method.toLowerCase();
    openapi.paths[pathKey] ||= {};
    if (openapi.paths[pathKey][method]) {
      throw new Error(`Duplicate OpenAPI operation: ${endpoint.method} ${endpoint.path}`);
    }

    const operation = {
      tags: [featureTag(endpoint.path, basePath)],
      summary: `${endpoint.task_id} - ${endpoint.method} ${endpoint.path}`,
      description: `Owned by ${endpoint.owner}. Priority: ${endpoint.priority}. Access: ${endpoint.access}.`,
      responses: {
        [endpoint.success_status]: {
          description: endpoint.response?.message || 'Success',
          content: { 'application/json': { example: endpoint.response } },
        },
        400: { description: 'Validation failed or invalid input' },
        401: { description: 'Missing, invalid, expired, or revoked access token' },
        403: { description: 'Inactive account or insufficient role' },
        500: { description: 'Unexpected server error' },
      },
    };

    const pathParameters = [...endpoint.path.matchAll(/:([A-Za-z][A-Za-z0-9_]*)/g)].map(
      ([, name]) => ({ name, in: 'path', required: true, schema: { type: 'string' } }),
    );
    const queryParameters = Object.entries(endpoint.query_example || {}).map(([name, example]) => ({
      name,
      in: 'query',
      required: false,
      schema: schemaForExample(example),
      example,
    }));
    if (pathParameters.length || queryParameters.length) {
      operation.parameters = [...pathParameters, ...queryParameters];
    }

    if (endpoint.request) {
      operation.requestBody = {
        required: true,
        content: { 'application/json': { example: endpoint.request } },
      };
    }

    if (endpoint.access !== 'Public') {
      operation.security =
        endpoint.path === `${basePath}/install` ? [{ SetupKey: [] }] : [{ BearerAuth: [] }];
    }

    openapi.paths[pathKey][method] = operation;
  }

  return openapi;
}

async function main() {
  const contracts = JSON.parse(fs.readFileSync(contractsPath, 'utf8'));
  const prettierConfig = (await prettier.resolveConfig(outputPath)) || {};
  const output = await prettier.format(JSON.stringify(buildOpenApi(contracts), null, 2), {
    ...prettierConfig,
    filepath: outputPath,
  });

  if (process.argv.includes('--check')) {
    if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== output) {
      throw new Error(
        'docs/api/openapi.json is stale. Run npm run generate:openapi and commit the result.',
      );
    }
    console.log('OpenAPI document matches docs/api/contracts.json.');
    return;
  }

  fs.writeFileSync(outputPath, output);
  console.log('Generated docs/api/openapi.json from docs/api/contracts.json successfully.');
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
